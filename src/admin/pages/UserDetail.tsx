const getActivityConfig = (type: string) => {
  const t = type.toUpperCase().replace(/\s+/g, '_');
  if (t.includes('COMPLETED') || t.includes('BOOKED')) {
    return {
      Icon: CheckCircle2,
      color: 'text-emerald-600 bg-emerald-50 border-emerald-100'
    };
  }
  if (t.includes('CHECK_IN') || t.includes('VISITED')) {
    return {
      Icon: UserCheck,
      color: 'text-blue-600 bg-blue-50 border-blue-100'
    };
  }
  if (t.includes('ALLOTMENT') || t.includes('ASSIGN') || t.includes('OVERRIDE')) {
    return {
      Icon: UserCheck,
      color: 'text-purple-600 bg-purple-50 border-purple-100'
    };
  }
  if (t.includes('CREATED') || t.includes('REGISTER') || t.includes('CREATE') || t.includes('SPAWNED')) {
    return {
      Icon: User,
      color: 'text-slate-600 bg-slate-50 border-slate-100'
    };
  }
  if (t.includes('NOTE') || t.includes('COMMENT')) {
    return {
      Icon: Clock,
      color: 'text-amber-600 bg-amber-50 border-amber-100'
    };
  }
  return {
    Icon: Activity,
    color: 'text-sky-600 bg-sky-50 border-sky-100'
  };
};

